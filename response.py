class RouteMetadata(BaseModel):
    """
    Query-routing information produced by the decision engine.
    """

    route: str = "unknown"

    confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
    )


class EvidenceItem(BaseModel):
    """
    Individual evidence supporting a business decision.
    """

    source: str
    metric: Optional[str] = None
    value: Any = None
    interpretation: Optional[str] = None
    confidence: Optional[float] = None


class RecommendationItem(BaseModel):
    """
    Actionable recommendation generated by the decision engine.
    """

    decision_type: Optional[str] = None

    entity_type: Optional[str] = None

    entity_id: Optional[str] = None

    entity_name: Optional[str] = None

    priority: Optional[str] = None

    score: Optional[float] = None

    reason: Optional[str] = None

    recommendation: Optional[str] = None

    evidence: List[Dict[str, Any]] = Field(
        default_factory=list
    )


class SourceItem(BaseModel):
    """
    Enterprise knowledge source retrieved by the RAG pipeline.
    """

    title: str

    source: Optional[str] = None

    score: float = 0.0


class DecisionResponse(BaseModel):
    """
    Standard response contract for the Enterprise AI
    Decision Intelligence Platform.

    This model creates a stable interface between the
    application service and presentation/API layers.
    """

    question: str

    answer: str

    route: RouteMetadata = Field(
        default_factory=RouteMetadata
    )

    kpis: Dict[str, Any] = Field(
        default_factory=dict
    )

    customer_insights: List[
        Dict[str, Any]
    ] = Field(
        default_factory=list
    )

    product_insights: List[
        Dict[str, Any]
    ] = Field(
        default_factory=list
    )

    evidence: List[EvidenceItem] = Field(
        default_factory=list
    )

    recommendations: List[
        RecommendationItem
    ] = Field(
        default_factory=list
    )

    sources: List[SourceItem] = Field(
        default_factory=list
    )

    rag_context: Optional[str] = None

    llm_used: bool = False

    evidence_available: bool = False

    metadata: Dict[str, Any] = Field(
        default_factory=dict
    )

    def to_dict(self) -> Dict[str, Any]:
        """
        Convert the response into a standard dictionary.

        Useful for Streamlit, APIs, logging and testing.
        """

        return self.model_dump()

    def to_json(self) -> str:
        """
        Serialize the response to JSON.
        """

        return self.model_dump_json()